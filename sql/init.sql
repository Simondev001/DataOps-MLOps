CREATE TABLE IF NOT EXISTS sensors (
    sensor_id TEXT PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS air_quality_measurements (
    measurement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id TEXT NOT NULL REFERENCES sensors(sensor_id),
    measured_at TIMESTAMPTZ NOT NULL,
    pm2_5 DOUBLE PRECISION CHECK (pm2_5 >= 0),
    pm10 DOUBLE PRECISION CHECK (pm10 >= 0),
    no2 DOUBLE PRECISION CHECK (no2 >= 0),
    o3 DOUBLE PRECISION CHECK (o3 >= 0),
    temperature DOUBLE PRECISION,
    humidity DOUBLE PRECISION CHECK (humidity BETWEEN 0 AND 100),
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS anomalies (
    anomaly_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id TEXT NOT NULL REFERENCES sensors(sensor_id),
    measurement_id BIGINT REFERENCES air_quality_measurements(measurement_id),
    detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    rule_code TEXT NOT NULL,
    description TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'medium'
        CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    UNIQUE (measurement_id, rule_code)
);

CREATE TABLE IF NOT EXISTS model_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id TEXT NOT NULL REFERENCES sensors(sensor_id),
    measurement_id BIGINT REFERENCES air_quality_measurements(measurement_id),
    predicted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    target_at TIMESTAMPTZ,
    model_name TEXT NOT NULL,
    model_version TEXT NOT NULL,
    prediction JSONB NOT NULL,
    anomaly_score DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS idx_measurements_sensor_time
    ON air_quality_measurements (sensor_id, measured_at DESC);

CREATE INDEX IF NOT EXISTS idx_measurements_time
    ON air_quality_measurements (measured_at DESC);

CREATE INDEX IF NOT EXISTS idx_anomalies_sensor_detected
    ON anomalies (sensor_id, detected_at DESC);

CREATE INDEX IF NOT EXISTS idx_predictions_sensor_predicted
    ON model_predictions (sensor_id, predicted_at DESC);
